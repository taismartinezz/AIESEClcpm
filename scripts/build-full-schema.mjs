// Concatenate every migration (in the order Supabase applies them) into a single
// supabase/full_schema.sql you can paste into the SQL editor of an EMPTY project.
// Run: npm run db:bundle   (CI/tests check the bundle is up to date and runs cleanly)
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "supabase", "migrations");
const files = readdirSync(dir).filter((f) => f.endsWith(".sql")).sort();

export function buildFullSchema() {
  const parts = [
    "-- AIESEClcpm: full database schema",
    "-- GENERATED by scripts/build-full-schema.mjs from supabase/migrations/. Do not edit by hand.",
    "-- Paste into the SQL editor of a NEW, empty Supabase project, or run the",
    "-- individual migrations in order instead. Both produce the same database.",
    "",
    "-- Already set up? Stop before changing anything (the whole script is one batch,",
    "-- so this error leaves the database exactly as it was).",
    "do $$",
    "begin",
    "  if to_regclass('public.departments') is not null then",
    "    raise exception 'This database is already set up: it has the app''s tables, so there is nothing to run. To apply a newer change, run only that file from supabase/migrations.';",
    "  end if;",
    "end $$;",
    "",
  ];
  for (const f of files) {
    parts.push(`-- ════════════════════════════════════════════════════════════════════════════`);
    parts.push(`-- ${f}`);
    parts.push(`-- ════════════════════════════════════════════════════════════════════════════`);
    parts.push(readFileSync(join(dir, f), "utf8").trimEnd(), "");
  }
  return parts.join("\n") + "\n";
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  writeFileSync(join(root, "supabase", "full_schema.sql"), buildFullSchema());
  console.log(`Wrote supabase/full_schema.sql from ${files.length} migrations.`);
}
